proof('chapter15.tex', r'用线性不变分解取坐标', r'''
\paragraph{线性分解与截断。}
在稳定、不稳定子空间中分别取坐标，写成
\[
 F(u,v)=(Su+f(u,v),Uv+g(u,v)),\qquad
 f(0)=g(0)=0,\quad Df(0)=Dg(0)=0.
\]
对 Jordan 块中的基向量作逐次缩放，可取等价范数，使
$\|S\|,\|U^{-1}\|\leq a<1$。两个子空间的乘积使用最大范数。
在半径 $r$ 的小球内，$Df,Dg$ 的范数随 $r\downarrow0$ 一致趋零。
取在半径 $r$ 球内为 1、半径 $2r$ 球外为零的光滑截断函数 $\chi_r$。
因 $|f(z)|,|g(z)|=o(|z|)$ 且 $|D\chi_r|=O(1/r)$，
乘积求导中的 $D\chi_r f,D\chi_r g$ 也一致趋零。
因此截断后的非线性项可具有任意小的全局 Lipschitz 常数 $L$。
以下先研究截断方程，最后限制回原小球。

\paragraph{将递推写成压缩方程。}
选 $a<\sigma<1$，在序列空间中置
\[
 \|z\|_\sigma=\sup_{n\geq0}\sigma^{-n}\max(|u_n|,|v_n|).
\]
乘以权 $\sigma^{-n}$ 将它等距对应到有界序列空间，因此该空间完备。
固定稳定坐标 $u_0=\xi$，定义算子 $\mathcal A_\xi$：
\begin{align*}
 (\mathcal A_\xi z)^s_n
 &=S^n\xi+\sum_{j=0}^{n-1}S^{n-1-j}f(z_j),\\
 (\mathcal A_\xi z)^u_n
 &=-\sum_{j=n}^\infty U^{n-1-j}g(z_j).
\end{align*}
第一式是稳定递推的逐次代入。第二式由
$v_n=U^{-1}v_{n+1}-U^{-1}g(z_n)$ 向未来迭代，并令终点趋于无穷得到。
若 $z$ 有界，则剩余项 $U^{n-N}v_N$ 因 $\|U^{-1}\|<1$ 而趋零。
反过来，把第二个和式的 $n$ 与 $n+1$ 项相减，即恢复不稳定递推，
故不动点确实给出一条轨道。

设 $d=\|z-\widetilde z\|_\sigma$。逐项估计为
\begin{align*}
 \sigma^{-n}|(\mathcal A_\xi z-\mathcal A_\xi\widetilde z)^s_n|
 &\leq Ld\sum_{j=0}^{n-1}a^{n-1-j}\sigma^{j-n}
 \leq\frac{L}{\sigma-a}d,\\
 \sigma^{-n}|(\mathcal A_\xi z-\mathcal A_\xi\widetilde z)^u_n|
 &\leq Ld\sum_{j=n}^\infty a^{j+1-n}\sigma^{j-n}
 =\frac{La}{1-a\sigma}d.
\end{align*}
而输入零序列时，右端为 $(S^n\xi,0)$，范数不超过 $|\xi|$。
所以算子将该空间映到自身。取 $L$ 使两常数的最大值 $q<1$，
Banach 定理给出唯一不动点 $z(\xi)$，且
\[
 \|z(\xi)\|_\sigma\leq\frac{|\xi|}{1-q},\qquad
 \|z(\xi)-z(\eta)\|_\sigma\leq\frac{|\xi-\eta|}{1-q}.
\]
因此这些轨道以 $\sigma^n$ 速度趋零。定义 $h(\xi)=v_0(\xi)$。
当 $|\xi|$ 足够小时，整条轨道均留在截断未改变方程的小球内。

\paragraph{光滑性与相切性。}
截断非线性项的各阶导数有界。将它逐项作用于加权序列，
其一阶余项由 $Df,Dg$ 的一致连续性控制。
第 $k$ 阶导数作用在 $k$ 个序列上时，逐项产生权 $\sigma^{kj}$；
因 $\sigma^{kj}\leq\sigma^j$，上述两种几何级数估计仍适用。
所以 $\mathcal A(\xi,z)$ 是 $C^r$ 映射，且 $\|D_z\mathcal A\|\leq q<1$。
从而
\[
 (I-D_z\mathcal A)^{-1}=\sum_{j=0}^\infty(D_z\mathcal A)^j,
 \qquad\|(I-D_z\mathcal A)^{-1}\|\leq(1-q)^{-1}.
\]
对不动点方程作差，并用刚得的 Lipschitz 估计控制其余项，得到
\[
 D_\xi z=(I-D_z\mathcal A)^{-1}D_\xi\mathcal A.
\]
余项除以 $|\Delta\xi|$ 趋零，故这是真正的 Fréchet 导数。
右端连续，因而 $z$ 为 $C^1$；继续求导时，最高阶未知导数仍乘
$I-D_z\mathcal A$，其余项只含已得到的低阶导数。由归纳得到 $C^r$。
取零初值，唯一不动点为零序列。由于 $Df(0)=Dg(0)=0$，
导数轨道恰为 $(S^n\xi,0)$，故 $h(0)=0,Dh(0)=0$。
图像 $\xi\mapsto(\xi,h(\xi))$ 的微分含恒等的第一分量，
是 $\dim E^s$ 维 $C^r$ 子流形，并与 $E^s$ 相切。

\paragraph{刻画局部稳定集。}
还需排除未被构造捕获的局部轨道。在不加权有界序列空间中，
同一算子的压缩常数分别为 $L/(1-a)$ 和 $La/(1-a)$。
进一步缩小 $L$，使它们也小于 1。任何始终留在小球的正向轨道都是有界序列，
由前面的递推求和满足同一个不动点方程。
有界不动点唯一，而已构造的加权不动点也是有界的，故两者相同。
所以这类轨道自动趋零，其初点必在图像上。
反之，图像上足够靠近零的点，其估计保证整条正向轨道留在小球并趋零。
在选择的局部邻域内，这正是局部稳定集。
将轨道序列左移一项仍是趋零轨道，故其下一点也在图像上，得到局部不变性。
对局部逆映射 $F^{-1}$ 重复同一构造，得到不稳定流形。
''')

proof('chapter15.tex', r'记稳定、不稳定投影为', r'''
\paragraph{双曲线性方程的有界逆。}
记稳定、不稳定投影为 $P_s,P_u$。由广义特征空间分解和 Jordan 指数估计，
存在 $K,c>0$，使
\[
 \|e^{tA}P_s\|\leq Ke^{-ct}\ (t\geq0),\qquad
 \|e^{tA}P_u\|\leq Ke^{ct}\ (t\leq0).
\]
在有界连续函数的完备空间 $C_b(\R,\R^n)$ 中，定义
\[
 (Gf)(t)=\int_{-\infty}^te^{A(t-s)}P_sf(s)\,ds
 -\int_t^\infty e^{A(t-s)}P_uf(s)\,ds.
\]
两积分绝对收敛，分别不超过 $K\|f\|_\infty/c$，故
$\|G\|\leq C_G:=2K/c$。在有限区间求导，再用指数尾项取极限，得
$(Gf)'=A(Gf)+f$。
若两个有界特解存在，其差为 $e^{tA}v$；稳定分量若非零则负向无界，
不稳定分量若非零则正向无界。因而差为零，$Gf$ 是唯一整轴有界特解。
由积分换元还可知，$G$ 与任意时间平移可交换。

\paragraph{从非线性轨道得到线性轨道。}
用小球截断 $R$。因为 $R(0)=DR(0)=0$，截断后可同时做到
$\|R\|_\infty\leq M$、$\operatorname{Lip}(R)=L$，并使 $q=C_GL<1$。
该截断在一个零点邻域内不改变原方程。
截断方程的向量场满足线性增长估计
$|Ax+R(x)|\leq\|A\||x|+M$；Gronwall 估计及有限端点延拓判据
保证其解双向全局存在，记流为 $\varphi^t$。
对初点 $x_0$ 的整条轨道 $x(t)$，函数 $R(x(t))$ 有界。
置
\[
 y(t)=x(t)-G(R(x))(t).
\]
由 Green 算子的方程，$y'=Ax+R(x)-[AG(R(x))+R(x)]=Ay$。
定义 $h(x_0)=y(0)$，时间平移可交换性于是给出
$h(\varphi^tx_0)=e^{tA}h(x_0)$。此外 $|h(x_0)-x_0|\leq C_GM$。

\paragraph{构造逆变换并验证互逆。}
固定任意 $y_0$，令 $y(t)=e^{tA}y_0$。尽管 $y$ 本身可能无界，
映射 $z\mapsto G(R(y+z))$ 仍将 $C_b$ 映入自身，因为 $R$ 全局有界。
其 Lipschitz 常数不超过 $q<1$，故存在唯一有界不动点
\[
 z=G(R(y+z)),\qquad \|z\|_\infty\leq C_GM.
\]
于是 $z'=Az+R(y+z)$，所以 $x=y+z$ 解非线性方程。定义 $k(y_0)=x(0)$。
对于这条轨道，$G(R(x))=z$，故 $h(k(y_0))=y_0$。
反过来，对任意非线性轨道所定义的 $y=x-G(R(x))$，
有界差 $z=x-y$ 满足同一不动点方程。唯一性说明逆构造恢复该 $x$，
所以 $k(h(x_0))=x_0$。这证明 $h,k$ 是互逆双射，且 $h(0)=0$。

\paragraph{连续性。}
先证 $h$ 在任意 $x_0$ 连续。对 $G(R(\varphi^{\cdot}x_0))(0)$ 的积分，
$|s|>B$ 的尾项不超过 $2KM e^{-cB}/c$，且与初点无关。
先选大 $B$ 使尾项小，再用紧时间段 $[-B,B]$ 内的初值连续依赖，
使有限部分的积分连续，便得 $h$ 连续。

为证 $k$ 连续，从 $z_0=0$ 开始迭代
$z_{j+1}=G(R(e^{\cdot A}y_0+z_j))$。
归纳地，每个 $z_j(t,y_0)$ 对 $(t,y_0)$ 连续：积分的远端仍由一致指数尾界控制，
有限部分使用被积函数在紧集上的连续性。
且压缩估计给出
\[
 \|z-z_j\|_\infty\leq\frac{q^j}{1-q}\|z_1-z_0\|_\infty
 \leq\frac{q^j C_GM}{1-q},
\]
这一界不依赖 $y_0$。因此 $z_j(0,y_0)$ 一致趋于连续函数 $z(0,y_0)$，
$k(y_0)=y_0+z(0,y_0)$ 连续。$h$ 因而是同胚。

最后取截断恒为 1 的零点邻域，并将全局共轭限制于该邻域及其像。
凡原轨道的一段始终留在此邻域，它与截断轨道相同，因而满足同一保时间共轭等式。
这正是原方程与线性方程的局部拓扑共轭。
''')
