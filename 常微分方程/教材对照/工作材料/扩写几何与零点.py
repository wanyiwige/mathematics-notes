proof('chapter7.tex',r'前两项由通常微分法则',r'''
对常数 $c_1,c_2$，偏导的线性性给出
$L_v(c_1f+c_2g)=c_1L_vf+c_2L_vg$；
乘积求导给出 $L_v(fg)=fL_vg+gL_vf$。

设 $f$ 至少二次连续可微。逐项展开为
\begin{align*}
 L_aL_bf&=\sum_{i,j}a_i(\partial_i b_j)\partial_jf
              +\sum_{i,j}a_ib_j\partial_i\partial_jf,\\
 L_bL_af&=\sum_{i,j}b_i(\partial_i a_j)\partial_jf
              +\sum_{i,j}b_ia_j\partial_i\partial_jf.
\end{align*}
交换第二个二阶和中的指标 $i,j$，再用混合偏导相等，两二阶和相消。
余下的一阶系数正是 $Db\,a-Da\,b$，所以得到交换子公式。

双线性和反对称性可直接从这个分量表达式检查。
为证明 Jacobi 恒等式，在算子复合的结合代数中展开
$[A,[B,C]]+[B,[C,A]]+[C,[A,B]]$：
每个三重乘积都出现两次且符号相反，因此和为零。
取 $A=L_a,B=L_b,C=L_c$ 并使用刚证的公式，得到某个向量场的微分算子为零。
而 $L_vx_j=v_j$，说明 $L_v=0$ 必推出 $v=0$。
所以对应向量场的 Jacobi 和也为零。
''')
