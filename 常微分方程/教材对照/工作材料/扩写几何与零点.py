proof('chapter8.tex',r'由初值唯一性，每个满足左端',r'''
\textbf{第一步：把边值问题化为一个相位方程。}
令 $x(t,\lambda)$ 解初值问题 $x(0,\lambda)=0,x'(0,\lambda)=1$。
任何非零解若在左端为零，其左端导数必不为零，
除以该导数后便与 $x(t,\lambda)$ 具有相同初值，因此由唯一性重合。
所以每个特征空间一维，特征值条件正是 $x(l,\lambda)=0$。
取 $\theta(0,\lambda)=0$，这个条件等价于 $\theta(l,\lambda)=k\pi$，$k\geq1$。

\textbf{第二步：证明末端相位对参数严格增加。}
参数可微依赖定理给出 $w=\partial_\lambda x$，并由对方程求导得到
$w''+(q+\lambda)w=-x$、$w(0)=w'(0)=0$。
逐项计算为
\[
 (x'w-xw')'=x''w-xw''=x^2.
\]
零初值使 $x'w-xw'=\int_0^t x(s,\lambda)^2ds$。
又由相位角的微分公式，
\[
 \partial_\lambda\theta(l,\lambda)
 =\frac{x'(l,\lambda)w(l,\lambda)-x(l,\lambda)w'(l,\lambda)}
 {x(l,\lambda)^2+x'(l,\lambda)^2}>0.
\]
分母不为零，分子积分严格为正，因为 $x'(0,\lambda)=1$。

\textbf{第三步：确定相位的取值范围并编号。}
当 $\lambda\leq-\max q$ 时，$q+\lambda\leq0$。
解从零以正速度出发；在保持正值的阶段有 $x''=-(q+\lambda)x\geq0$，
所以导数不能降到零，解不可能再次为零。
因此末端相位位于 $(0,\pi)$。
另一方面，给定任意正整数 $N$，可取 $\lambda$ 足够大，使
$q+\lambda\geq\omega^2$ 且 $N\pi/\omega<l$。
比较定理使 $x$ 在 $[0,l]$ 有至少 $N$ 次零点穿越，故末端相位趋于无穷。
连续性与严格单调性说明每个水平 $k\pi$ 恰穿过一次，给出严格递增的 $\lambda_k$。
相邻零点角增为 $\pi$，故第 $k$ 个特征函数恰有 $k-1$ 个内部零点。
若 $\lambda_k$ 有有限聚点，末端相位在该紧参数区间有界，
但其值 $k\pi$ 无界，矛盾，所以 $\lambda_k\to\infty$。

\textbf{第四步：比较常系数方程以估计特征值。}
记 $\mu_k=(k\pi/l)^2$。
在 $\lambda=\mu_k-M$ 时有 $q+\lambda\leq\mu_k$，
由同初始角的标量比较，末端相位不超过常系数方程的 $k\pi$。
在 $\lambda=\mu_k-m$ 时有反向不等式，末端相位不小于 $k\pi$。
由末端相位严格随 $\lambda$ 增加，得到
$\mu_k-M\leq\lambda_k\leq\mu_k-m$。
两边除以 $k^2$ 后，常数误差趋于零，夹逼得到所述渐近式。
''')
